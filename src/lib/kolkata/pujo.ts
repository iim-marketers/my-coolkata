/**
 * Durga Puja follows a lunisolar calendar, so the date moves. These are
 * the published Mahasasthi dates; the countdown targets the next one.
 */
export const pujoDates: Record<number, string> = {
  2025: "2025-09-28",
  2026: "2026-10-17",
  2027: "2027-10-07",
  2028: "2028-09-25",
  2029: "2029-10-13",
  2030: "2030-10-02",
};

export function nextPujoStart(now = new Date()): { date: Date; year: number } {
  const years = Object.keys(pujoDates)
    .map(Number)
    .sort((a, b) => a - b);
  for (const y of years) {
    const d = new Date(`${pujoDates[y]}T06:00:00+05:30`);
    if (d.getTime() > now.getTime()) return { date: d, year: y };
  }
  const last = years[years.length - 1];
  return { date: new Date(`${pujoDates[last]}T06:00:00+05:30`), year: last };
}
